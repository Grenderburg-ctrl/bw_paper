# Rows of one panel: genes on the plot of the given classes, with an "auxiliary subunits" sub-header row
# inserted before the first auxiliary family of each class.
make_rows <- function(classes, tiers) {
  d <- genes[genes$class %in% classes & genes$tier %in% tiers & genes$on_plot, ]
  d <- d[order(d$order), ]
  fams <- unique(d$family)
  out <- list()
  for (f in fams) {
    x <- d[d$family == f, ]
    cl <- x$class[1]
    first_aux_of_class <- x$tier[1] == "auxiliary" && !any(d$class == cl & d$tier == "auxiliary" & d$order < min(x$order))
    if (first_aux_of_class) {
      blank <- x[1, setdiff(names(x), "family"), drop = FALSE]
      blank[1, ] <- NA
      out[[length(out) + 1]] <- cbind(data.frame(fam = paste0("hdr_", cl), id = paste0("hdr_", cl), lab = hdr_html,
                                                 is_hdr = TRUE, stringsAsFactors = FALSE), blank)
    }
    r <- cbind(data.frame(fam = f, id = x$gene, lab = sprintf("*%s* (%s)", x$gene, x$protein), is_hdr = FALSE,
                          stringsAsFactors = FALSE), x[, setdiff(names(x), "family"), drop = FALSE])
    out[[length(out) + 1]] <- r
  }
  r <- do.call(rbind, out)
  r$fam <- factor(r$fam, unique(r$fam))
  r$id_f <- factor(r$id, rev(r$id))
  r$y <- ave(seq_len(nrow(r)), r$fam, FUN = function(i) rev(seq_along(i)))   # position inside the facet (1 = bottom)
  r$status[r$is_hdr] <- NA
  r
}

# Whiskers, clipping and labels (rows that are not headers).
prep_rows <- function(r) {
  r$x <- ifelse(r$is_hdr, 0, pmin(pmax(r$log2FoldChange, XL[1]), XL[2]))
  r$clip_hi <- !r$is_hdr & r$log2FoldChange > XL[2]
  r$clip_lo <- !r$is_hdr & r$log2FoldChange < XL[1]
  r$lo <- r$log2FoldChange - r$lfcSE; r$hi <- r$log2FoldChange + r$lfcSE
  r$wl <- pmax(r$lo, XL[1]); r$wh <- pmin(r$hi, XL[2])
  r$w_draw <- !r$is_hdr & r$wl < r$wh
  r$cap_lo <- r$w_draw & r$lo >= XL[1]; r$cap_hi <- r$w_draw & r$hi <= XL[2]
  r$p_lab <- ifelse(r$is_hdr, NA, ifelse(r$status == "ns", '"ns"', fmt_p_math(r$padj, 2)))
  r$stars <- ifelse(r$is_hdr | r$status == "ns", NA, p_stars(r$padj))
  r
}

tri_df <- function(r) {                                       # triangles pointing outwards at the axis edge
  b <- r[r$clip_hi | r$clip_lo, ]
  if (!nrow(b)) return(b[0, c("id", "status", "low_expr")][, c("id", "status", "low_expr")])
  do.call(rbind, lapply(seq_len(nrow(b)), function(i) {
    s <- if (b$clip_hi[i]) 1 else -1
    data.frame(id = b$id[i], status = b$status[i], low_expr = b$low_expr[i], fam = b$fam[i],
               px = XL[if (s > 0) 2 else 1] - s * c(0, 0.34, 0.34),
               py = b$y[i] + c(0, 0.34, -0.34))
  }))
}

strip_lab <- function(x) ifelse(grepl("^hdr_", x), "", sub(" \\(", "\n(", x))

miss_text <- function(r_all, classes, tiers) {
  x <- genes[genes$class %in% classes & genes$tier %in% tiers & genes$status %in% c("n.t.", "n.d."), ]
  line <- function(st) {
    y <- x[x$status == st, ]
    if (!nrow(y)) return("none")
    parts <- vapply(split(y$gene, droplevels(y$family_f)), function(g) paste0("*", g, "*", collapse = ", "), character(1))
    # digit/digit inside bold text falls back to DejaVu in gridtext: keep the slash outside the bold span
    fam_md <- gsub("(?<=[0-9])/(?=[0-9])", "**/**", names(parts), perl = TRUE)
    paste(sprintf("**%s:** %s", fam_md, parts), collapse = "; ")
  }
  md <- paste0("**Not tested** (padj = NA): ", line("n.t."), "; **not detected:** ", line("n.d."))
  plain <- gsub("[*]", "", md)
  list(md = md, n_lines = ceiling(nchar(plain) / 62))
}

# One panel = a single ggplot (forest + padj/stars columns drawn outside the plot area, so rows always align)
# converted to a gtable whose panel heights are fixed in mm (row pitch = row_mm); the n.t./n.d. note is a gridtext box.
col_w <- 84                                                   # mm; two columns on a 170-mm page, 2-mm gutter
page_w <- 170

build_panel <- function(classes, tiers, tag, unit_mm = 5, star_mm = 11.5) {
  r <- prep_rows(make_rows(classes, tiers))
  nrow_tot <- nrow(r); nfac <- nlevels(r$fam)
  lab <- setNames(r$lab, r$id)
  tri <- tri_df(r)
  nm <- r[!r$is_hdr, ]
  base <- theme_ijms() +
    theme(axis.text.y = ggtext::element_markdown(size = 7, family = FONT, hjust = 1, colour = "black"),
          axis.ticks.y = element_blank(),
          strip.placement = "outside", strip.text.y.left = element_text(angle = 0, hjust = 1, face = "bold", size = 7,
                                                                       lineheight = 0.9),
          panel.spacing.y = unit(gap_mm, "mm"), strip.clip = "off",
          plot.margin = margin(top_mm, pcol_mm, 1, 1, "mm"), plot.tag.position = c(0, 1))
  xp <- XL[2] + 0.2                                           # padj column starts just right of the axis
  pF <- ggplot(r, aes(x, id_f)) +
    geom_blank() +
    geom_vline(xintercept = 0, linewidth = lw_axis, colour = "#808080", linetype = "dashed") +
    geom_segment(data = nm[nm$w_draw, ], aes(x = wl, xend = wh, yend = id_f, colour = status), linewidth = lw_whisker) +
    geom_segment(data = nm[nm$cap_lo, ], aes(x = lo, xend = lo, y = y - 0.25, yend = y + 0.25, colour = status), linewidth = lw_whisker) +
    geom_segment(data = nm[nm$cap_hi, ], aes(x = hi, xend = hi, y = y - 0.25, yend = y + 0.25, colour = status), linewidth = lw_whisker) +
    geom_point(data = nm[!nm$clip_hi & !nm$clip_lo & !nm$low_expr, ], aes(colour = status), size = 1.6) +
    geom_point(data = nm[!nm$clip_hi & !nm$clip_lo & nm$low_expr, ], aes(colour = status), shape = 21, fill = "white",
               size = 1.6, stroke = 0.5) +
    geom_polygon(data = tri[!tri$low_expr, ], aes(px, py, group = id, colour = status, fill = status), linewidth = 0.2,
                 inherit.aes = FALSE) +
    geom_polygon(data = tri[tri$low_expr, ], aes(px, py, group = id, colour = status), fill = "white", linewidth = 0.4,
                 inherit.aes = FALSE) +
    geom_text(data = nm[nm$clip_hi, ], aes(x = XL[2] - 0.45, label = paste0("+", formatC(log2FoldChange, format = "f", digits = 2))),
              hjust = 1, size = 6 / PT, family = FONT) +
    geom_text(data = nm[nm$clip_lo, ], aes(x = XL[1] + 0.45, label = fmt_num(log2FoldChange, 2)),
              hjust = 0, size = 6 / PT, family = FONT) +
    geom_text(data = nm, aes(x = xp, label = p_lab), parse = TRUE, hjust = 0, size = 6.5 / PT, family = FONT) +
    geom_text(data = nm[!is.na(nm$stars), ], aes(x = xp + star_mm / unit_mm, label = stars), hjust = 0, size = 6.5 / PT, family = FONT) +
    facet_grid(fam ~ ., scales = "free_y", space = "free_y", switch = "y", labeller = as_labeller(strip_lab)) +
    scale_colour_manual(values = dir_cols, guide = "none") + scale_fill_manual(values = dir_cols, guide = "none") +
    scale_y_discrete(labels = function(i) lab[as.character(i)], expand = expansion(add = 0.5)) +
    scale_x_continuous(breaks = seq(-3, 3, 1), labels = lab_minus) +
    coord_cartesian(xlim = XL, expand = FALSE, clip = "off") +
    labs(x = expression(log[2] ~ "fold change (rLLB vs. Control)"), y = NULL, tag = tag) +
    base

  g <- ggplotGrob(pF)
  pan <- g$layout[grepl("^panel", g$layout$name), ]
  pan <- pan[order(pan$t), ]
  n_per <- as.integer(table(r$fam)[levels(r$fam)])
  g$heights[pan$t] <- unit(n_per * row_mm, "mm")             # fixed row pitch
  g$widths[unique(pan$l)] <- unit(1, "null")

  mt <- miss_text(r, classes, tiers)
  tg <- gridtext::textbox_grob(mt$md, x = unit(0, "mm"), y = unit(1, "npc"), hjust = 0, vjust = 1, halign = 0,
                               width = unit(col_w - 1, "mm"), padding = unit(c(0, 0, 0, 0), "mm"),
                               gp = grid::gpar(fontsize = 6.5, fontfamily = FONT, lineheight = 1.25),
                               box_gp = grid::gpar(col = NA, fill = NA))
  list(gt = g, tg = tg, pan_first = pan[1, ], rows = r, n_rows = sum(!r$is_hdr), n_hdr = sum(r$is_hdr))
}

# Measure (mm) a built panel on a scratch device, so that the page height follows from the content.
measure_panel <- function(P) {
  grDevices::cairo_pdf(tempfile(fileext = ".pdf"), width = 6, height = 8, family = FONT)
  on.exit(invisible(dev.off()))
  grid::pushViewport(grid::viewport(width = unit(col_w, "mm"), height = unit(250, "mm")))
  P$h_gt <- grid::convertHeight(sum(P$gt$heights), "mm", valueOnly = TRUE)
  P$h_tg <- grid::convertHeight(grid::grobHeight(P$tg), "mm", valueOnly = TRUE)
  P$top_above_panel <- grid::convertHeight(sum(P$gt$heights[seq_len(P$pan_first$t - 1)]), "mm", valueOnly = TRUE)
  P$right_of_panel <- grid::convertWidth(sum(P$gt$widths[(P$pan_first$r + 1):length(P$gt$widths)]), "mm", valueOnly = TRUE)
  P$panel_w <- col_w - grid::convertWidth(sum(P$gt$widths[-unique(P$pan_first$l)]), "mm", valueOnly = TRUE)
  P$h <- P$h_gt + 1 + P$h_tg
  P
}

# Draw a panel with its top-left corner at (x0, y_top) mm on the page.
draw_panel <- function(P, x0, y_top) {
  grid::pushViewport(grid::viewport(x = unit(x0, "mm"), y = unit(y_top, "mm"), width = unit(col_w, "mm"),
                                    height = unit(P$h_gt, "mm"), just = c("left", "top")))
  grid::grid.draw(P$gt)
  grid::grid.text("padj", x = unit(col_w - P$right_of_panel + 1.2, "mm"), y = unit(P$h_gt - P$top_above_panel + 0.8, "mm"),
                  just = c("left", "bottom"), gp = grid::gpar(fontsize = 7, fontface = "bold", fontfamily = FONT))
  grid::popViewport()
  grid::pushViewport(grid::viewport(x = unit(x0, "mm"), y = unit(y_top - P$h_gt - 1, "mm"), width = unit(col_w, "mm"),
                                    height = unit(P$h_tg, "mm"), just = c("left", "top")))
  grid::grid.draw(P$tg)
  grid::popViewport()
}

