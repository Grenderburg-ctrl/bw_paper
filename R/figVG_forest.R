## ------------------------------------------------------------ VG ledger ---
vg_checks <- data.frame(section = character(), check = character(), expected = character(),
                        obtained = character(), ok = logical(), stringsAsFactors = FALSE)
vg_notes <- list()
vg_check <- function(section, check, expected, obtained, ok) {
  vg_checks[nrow(vg_checks) + 1, ] <<- list(section, check, as.character(expected), as.character(obtained), isTRUE(ok))
  cat(sprintf("[VG %s] %-52s expected %-26s obtained %-26s %s\n", section, check, expected, obtained,
              if (isTRUE(ok)) "OK" else "MISMATCH"))
  invisible(isTRUE(ok))
}
vg_note <- function(section, ...) vg_notes[[section]] <<- c(vg_notes[[section]], paste0(...))
vg_title <- c(`4.1` = "Counts by status (section 4.1)", `4.2` = "Reference values (section 4.2)",
              `4.3.1` = "Symbols not found in counts", `4.3.2` = "Genes not detected (n.d.): absent vs. filtered",
              `4.3.3` = "Genes with low_expr (mean normalised counts < 5 in at least one group)",
              `4.3.4` = "Genes beyond the x axis", `4.3.5` = "Cook's distance", Layout = "Layout",
              Fonts = "Fonts and files", Session = "sessionInfo()", Source = "Gene list and nomenclature")
write_vg_report <- function() {
  f <- file.path(dir_fig, "figure_qc_VG.md")
  md <- c("# Figure QC report (FigVG, FigVG_ext)", "",
          sprintf("Generated by `R/figVG_forest.R` on %s. Statistics: `results/deseq2_R_results_no_exclusion.csv` (DESeq2 run2, no gene exclusion), padj < 0.05, no log2FC threshold, no LFC shrinkage.",
                  format(Sys.time(), "%Y-%m-%d %H:%M %Z")), "")
  if (!is.null(vg_notes[["STOP"]])) md <- c(md, "## STOPPED", "", paste0("**", vg_notes[["STOP"]], "**"), "")
  md <- c(md, "## Checks: expected / obtained / OK", "", "| section | check | expected | obtained | OK |", "|---|---|---|---|---|",
          sprintf("| %s | %s | %s | %s | %s |", vg_checks$section, gsub("|", "\\|", vg_checks$check, fixed = TRUE),
                  vg_checks$expected, vg_checks$obtained, ifelse(vg_checks$ok, "✅", "❌")), "")
  for (s in setdiff(names(vg_notes), "STOP")) {
    md <- c(md, paste0("## ", if (s %in% names(vg_title)) vg_title[[s]] else s), "")
    md <- c(md, unlist(lapply(vg_notes[[s]], function(x) c(x, ""))))
  }
  writeLines(md, f); message("wrote ", f)
}
vg_stop_if_failed <- function(sections) {
  bad <- vg_checks[vg_checks$section %in% sections & !vg_checks$ok, ]
  if (nrow(bad) > 0) {
    vg_note("STOP", "Stopped after section(s) ", paste(sections, collapse = ", "), ": ",
            paste(sprintf("%s (expected %s, obtained %s)", bad$check, bad$expected, bad$obtained), collapse = "; "),
            ". Figures were not built; no parameters were adjusted to the expected numbers.")
    write_vg_report()
    stop("VG QC failed: ", paste(bad$check, collapse = "; "))
  }
}

